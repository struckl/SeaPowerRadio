"""Writes src/SeaPowerRadio/Radio/ClipRules.g.cs: the plugin's copy of rules.py and of the phrase facts it needs.

Run after changing rules.py or a phrase in phrases.py: `python tools/voicegen/rules_cs.py`. check_sync.py renders
the file again and fails when the committed one differs.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import rules  # noqa: E402
from paths import REPO  # noqa: E402
from phrases import NAMED_VARIANTS, PHRASES, queued_max  # noqa: E402

TARGET = REPO / "src" / "SeaPowerRadio" / "Radio" / "ClipRules.g.cs"


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.split("_"))


def cs_float(value: float) -> str:
    return f"{value!r}f" if isinstance(value, float) else f"{value}f"


def cs_strings(values) -> str:
    return "{ " + ", ".join(f'"{v}"' for v in values) + " }"


def variant_position(phrase: str, text: str) -> int:
    variants = next(p.variants for p in PHRASES if p.key == phrase)
    return variants.index(text) + 1


def ranges() -> list[str]:
    out = []
    for name, (low, high) in (("Flight", rules.FLIGHTS), ("Position", rules.POSITIONS),
                              ("CallsignNumber", rules.CALLSIGN_NUMBERS), ("Angels", rules.ANGELS),
                              ("Count", rules.COUNTS)):
        out.append(f"    public const int {name}Min = {low}, {name}Max = {high};")
    hundreds = ", ".join(str(h) for h in rules.LOW_ALTITUDE_HUNDREDS)
    out.append(f"    public static readonly int[] LowAltitudeHundreds = {{ {hundreds} }};")
    out.append(f"    public static readonly string[] NumberPieces = {cs_strings(rules.NUMBER_PIECES)};")
    out.append(f"    public const float NumberPause = {cs_float(rules.NUMBER_PAUSE)}, "
               f"GroupPause = {cs_float(rules.GROUP_PAUSE)}, SpokenPause = {cs_float(rules.SPOKEN_PAUSE)};")
    out.append(f'    public const string SlugNot = "{rules.SLUG_NOT}", SlugEmpty = "{rules.SLUG_EMPTY}";')
    out.append(f"    public const int AlertMaxPriority = {rules.ALERT_MAX_PRIORITY}, "
               f"RoutineMinPriority = {rules.ROUTINE_MIN_PRIORITY}, ReplyPriority = {rules.REPLY_PRIORITY};")
    out.append(f"    public const int QueuedMax = {queued_max()};")
    return out


def callsign_words() -> list[str]:
    out = ["    public static readonly Dictionary<CallsignKind, string[]> CallsignWords = "
           "new Dictionary<CallsignKind, string[]>", "    {"]
    for kind, words in rules.CALLSIGN_WORDS.items():
        out.append(f"        [CallsignKind.{kind}] = new[] {cs_strings(words)},")
    out.append("    };")
    return out


def variants() -> list[str]:
    out = ["    /// <summary>Positions of the variants named in phrases.NAMED_VARIANTS.</summary>",
           "    public static class Variant", "    {"]
    for phrase, named in NAMED_VARIANTS.items():
        for name, text in named.items():
            out.append(f"        public const int {phrase}_{name} = {variant_position(phrase, text)};")
    out.append("    }")
    return out


def groups() -> list[str]:
    out = [f"    public static readonly string[] {name} = {cs_strings(keys)};"
           for name, keys in rules.PHRASE_GROUPS.items()]
    return out


def sound() -> list[str]:
    out = ["    public sealed class Profile",
           "    {",
           "        public readonly float Hiss, Crackle, Lp, Hp;",
           "        public Profile(float hiss, float crackle, float lp, float hp) "
           "{ Hiss = hiss; Crackle = crackle; Lp = lp; Hp = hp; }",
           "    }",
           "",
           "    public static readonly Dictionary<string, Profile> Profiles = new Dictionary<string, Profile>",
           "    {"]
    for name, p in rules.PROFILES.items():
        args = ", ".join(cs_float(p[k]) for k in ("hiss", "crackle", "lp", "hp"))
        out.append(f'        ["{name}"] = new Profile({args}),')
    out += ["    };", f'    public const string DefaultProfile = "{rules.DEFAULT_PROFILE}";', ""]
    out += [f"    public const float Fx{pascal(k)} = {cs_float(v)};" for k, v in rules.FX.items()]
    return out


def render() -> str:
    lines = [
        "// Generated by tools/voicegen/rules_cs.py from tools/voicegen/rules.py and phrases.py: change them there and",
        "// run the script again. check_sync.py fails while this file is out of date.",
        "using System.Collections.Generic;",
        "using SeaPowerRadio.Voices;",
        "",
        "namespace SeaPowerRadio.Radio;",
        "",
        "/// <summary>The clip and sound rules the plugin shares with the voice tools.</summary>",
        "internal static class ClipRules",
        "{",
    ]
    for part in (callsign_words(), ranges(), variants(), groups(), sound()):
        lines += part + [""]
    lines[-1] = "}"
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(REPO)}")
