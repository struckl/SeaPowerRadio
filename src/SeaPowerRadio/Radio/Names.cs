using System;
using System.Collections.Generic;
using System.IO;
using System.Text.RegularExpressions;

namespace SeaPowerRadio.Radio;

/// <summary>An in-game name the voice library can say, and the voices it was rendered in.</summary>
internal sealed class GameName
{
    public string Key;       // nm_<slug> (ship / shore unit) or sq_<slug> (squadron callsign word)
    public string Text;      // as the game writes it
    public bool Squadron;
    public string[] Voices;  // bound voices, best first (tools/voicegen/names.py)
}

/// <summary>
/// In-game names (mod/voices/names.txt, generated by tools/voicegen/names.py). Ships and shore units say their
/// short name ("Pargo"), player aircraft their squadron callsign ("Lancer 3", wingman "Lancer 3-2"). Each name
/// only exists in the few voices bound to it, which is why the roster gives named units those voices.
/// </summary>
internal static class Names
{
    private static readonly Dictionary<string, GameName> ByKey = new Dictionary<string, GameName>();
    private static readonly Regex NotSlug = new Regex("[^a-z0-9]+", RegexOptions.Compiled);
    private static readonly Regex AircraftName = new Regex(@"^(.*?)\s+(\d+)(?:-(\d+))?$", RegexOptions.Compiled);

    public static void Load(string voicesDirectory)
    {
        ByKey.Clear();
        string file = Path.Combine(voicesDirectory, "names.txt");
        if (!File.Exists(file))
        {
            ModLog.Warn("names.txt missing: units use generated callsigns.");
            return;
        }
        foreach (string raw in File.ReadAllLines(file))
        {
            string line = raw.Trim();
            if (line.Length == 0 || line.StartsWith("#")) continue;
            string[] f = line.Split('|');
            if (f.Length < 4) continue;
            ByKey[f[0]] = new GameName
            {
                Key = f[0],
                Text = f[1],
                Squadron = f[2] == "squadron",
                Voices = f[3].Split(new[] { ',' }, StringSplitOptions.RemoveEmptyEntries),
            };
        }
        ModLog.Info($"In-game names: {ByKey.Count}.");
    }

    /// <summary>Must match slug() in tools/voicegen/names.py.</summary>
    public static string Slug(string text)
    {
        string s = NotSlug.Replace((text ?? "").ToLowerInvariant(), "_").Trim('_');
        return s.Length == 0 ? "x" : s;
    }

    public static GameName Unit(string shortName) =>
        string.IsNullOrEmpty(shortName) ? null : ByKey.TryGetValue("nm_" + Slug(shortName), out GameName n) ? n : null;

    public static GameName SquadronWord(string word) =>
        string.IsNullOrEmpty(word) ? null : ByKey.TryGetValue("sq_" + Slug(word), out GameName n) ? n : null;

    /// <summary>"Lancer 3" → (Lancer, 3, 0); "Lancer 3-2" → (Lancer, 3, 2). False if it isn't callsign-shaped.</summary>
    public static bool TryParseAircraft(string name, out string word, out int number, out int position)
    {
        word = null;
        number = position = 0;
        if (string.IsNullOrEmpty(name)) return false;
        Match m = AircraftName.Match(name.Trim());
        if (!m.Success) return false;
        word = m.Groups[1].Value;
        number = int.Parse(m.Groups[2].Value);
        if (m.Groups[3].Success) position = int.Parse(m.Groups[3].Value);
        return true;
    }
}
